// Writes THIRD_PARTY_NOTICES.md: the license of every package that ends up inside Library (the production
// dependency tree), plus the decoders pdf.js ships as WebAssembly and the Electron runtime of the desktop app.
// Run `npm run notices` after adding, removing or upgrading a dependency.
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm'
const tree = execFileSync(npm, ['ls', '--omit=dev', '--all', '--parseable'], { cwd: root, encoding: 'utf8', shell: process.platform === 'win32' })
const dirs = [...new Set(tree.split(/\r?\n/).filter((d) => d && path.resolve(d) !== root))]

// Prebuilt binaries for one OS (only the current machine's are installed) and type-only packages never reach the app.
const SKIP = /(^@types\/|^csstype$|-(linux|darwin|win32|android|freebsd)-)/

const NOTES = {
  '@tesseract.js-data/eng': 'Packages the English model from tesseract-ocr/tessdata_best (https://github.com/tesseract-ocr/tessdata_best), licensed Apache-2.0.',
}

function link(url) {
  if (!url) return ''
  url = url.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/\.git(#.*)?$/, '')
  return /^[\w.-]+\/[\w.-]+$/.test(url) ? `https://github.com/${url}` : url
}

const LICENSE_FILE = /^(licen[sc]e|copying|notice)(\.(md|txt|markdown))?$/i

function licenseText(dir) {
  const files = fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort()
  return files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').trim()).join('\n\n')
}

function describe(dir, name, version, license, homepage) {
  return { name, version, license, homepage, text: licenseText(dir) }
}

const packages = []
for (const dir of dirs) {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
  if (SKIP.test(pkg.name)) continue
  const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? pkg.licenses?.map((l) => l.type).join(' OR ') ?? 'See license text')
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  packages.push({ ...describe(dir, pkg.name, pkg.version, license, link(pkg.homepage ?? repo)), note: NOTES[pkg.name] })
}

const electronDir = path.join(root, 'node_modules', 'electron')
const electron = JSON.parse(fs.readFileSync(path.join(electronDir, 'package.json'), 'utf8'))
packages.push({
  ...describe(electronDir, 'electron', electron.version, electron.license, 'https://www.electronjs.org'),
  note: 'The desktop app runs on Electron, which includes Chromium. The full Chromium license list ships beside the app as LICENSES.chromium.html.',
})

const wasmDir = path.join(root, 'node_modules', 'pdfjs-dist', 'wasm')
for (const [file, name] of [
  ['LICENSE_OPENJPEG', 'OpenJPEG (JPEG 2000 decoder, built into pdf.js)'],
  ['LICENSE_QCMS', 'qcms (colour management, built into pdf.js)'],
]) {
  packages.push({ name, version: '', license: 'See license text', homepage: '', text: fs.readFileSync(path.join(wasmDir, file), 'utf8').trim() })
}

packages.sort((a, b) => a.name.localeCompare(b.name))

const lines = [
  '# Third-party notices',
  '',
  'Library is built on the open-source work below. Each component keeps its own license, reproduced here.',
  'This file is generated by `npm run notices`; please don\'t edit it by hand.',
  '',
  '| Component | Version | License |',
  '| --- | --- | --- |',
  ...packages.map((p) => `| ${p.homepage ? `[${p.name}](${p.homepage})` : p.name} | ${p.version} | ${p.license} |`),
  '',
]
for (const p of packages) {
  lines.push('---', '', `## ${p.name}${p.version ? ` ${p.version}` : ''}`, '', `License: ${p.license}`, '')
  if (p.note) lines.push(p.note, '')
  lines.push(p.text ? '```text\n' + p.text.replace(/```/g, "'''") + '\n```' : '_No license file is included in this package; see its license field above._', '')
}

fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'))
console.log(`Wrote notices for ${packages.length} components.`)
